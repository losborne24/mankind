import './glb-node-images.mjs';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { loadTypescript } from './lib/load-typescript.mjs';
const mod = async path => import(await loadTypescript(path));
const { portunusJourney: journey } = await mod('lib/scenarios/portunus');
const { london2012 } = await mod('lib/scenarios/london2012');
const { validateScenario } = await mod('lib/scenarios/schema');
const { HistoricalDatasetSession } = await mod('lib/history/session');
const { ScenarioPlayer } = await mod('lib/scenarios/player');
const { HistoricalJourneyScenes, historicalModelStatus } = await mod('lib/scenarios/historicalScenes');
const world = JSON.parse(await readFile('lib/history/fixtures/portunus.json', 'utf8'));
validateScenario(journey);
for (const edit of [s => delete s.historicalDataset, s => delete s.content.scenes[0].historicalSceneId]) { const copy = structuredClone(journey); edit(copy); assert.throws(() => validateScenario(copy)); }
let time = { start: { year: 2025 } }, listener, applied, pose = { center: [30, 25], zoom: 2, pitch: 0, bearing: 0 };
let frames = new Map(), nextId = 0, now = 0, requests = 0;
const session = new HistoricalDatasetSession({ time: () => time, subscribeTime: fn => { listener = fn; return () => {}; }, apply: s => applied = s, release: () => applied = null, load: async () => { requests++; return world; } });
const scenes = new HistoricalJourneyScenes(session, { portunus: world });
const player = new ScenarioPlayer({ camera: { read: () => structuredClone(pose), write: value => pose = value, stop() {} }, timeline: value => { time = value; listener(); }, overlays() {}, scenes: (...args) => scenes.resolve(...args), releaseScenes: () => scenes.release(), frame: callback => { frames.set(++nextId, callback); return nextId; }, cancelFrame: id => frames.delete(id) });
const advance = count => { for (let i = 0; i < count; i++) { now += 100; const callbacks = [...frames.values()]; frames.clear(); callbacks.forEach(fn => fn(now)); assert.ok(frames.size <= 1); } };
player.load(journey); assert.equal(applied, undefined, 'Idle never adopts or renders a world');
player.play(); assert.equal(time.start.year, 100); assert.equal(applied.descriptors.length, 0, 'Overview is geographic context only');
session.inspect({ kind: 'place', id: world.places[0].id });
player.pause(); assert.equal(session.previewReconstruction(world.layouts[0].id), true, 'Explicit inspection can show the interpretation during overview exploration');
player.resume(); assert.equal(applied.descriptors.length, 0, 'Resume restores the overview scene plan');
player.jump(1); assert.equal(applied.descriptors.length, 1); assert.equal(player.snapshot.warning, undefined);
assert.equal(applied.scenes[0].assets[0].catalogue.entry.version, 1);
advance(30); const elapsed = player.snapshot.elapsed;
player.exploreFreely(); assert.equal(frames.size, 0); assert.equal(applied.descriptors.length, 1, 'Exploration retains the current building');
pose = { ...pose, center: [12.5, 41.9] }; time = { start: { year: 101 } }; listener();
assert.equal(applied.descriptors.length, 0);
player.resume(); assert.equal(time.start.year, 100); assert.equal(applied.descriptors.length, 1);
assert.equal(player.snapshot.elapsed, elapsed); advance(20); assert.equal(player.snapshot.returning, false);
player.jump(2); assert.equal(applied.descriptors.length, 1); assert.equal(player.snapshot.beat, 2);
player.restart(); assert.equal(applied.descriptors.length, 0, 'Restart releases detail before the approach');
player.jump(3); advance(60); assert.equal(player.snapshot.state, 'completed'); assert.equal(applied.descriptors.length, 1);
player.exploreFreely(); assert.equal(applied.descriptors.length, 1);
player.stop(); assert.equal(applied, null); assert.equal(frames.size, 0);
await session.load('portunus'); player.load(london2012); assert.ok(applied, 'A non-owned manual dataset is not released by switching journeys');
player.load(journey); player.jump(1); player.load(london2012); assert.equal(applied, null, 'Switching releases journey-owned scenes');
const optional = structuredClone(journey); optional.content.scenes[0].historicalSceneId = 'scene:missing';
player.load(optional); player.jump(1); assert.equal(player.snapshot.state, 'preparing'); assert.match(player.snapshot.warning, /context only/); assert.equal(applied, null);
const required = structuredClone(optional); required.content.scenes[0].required = true;
player.load(required); player.jump(1); assert.equal(player.snapshot.state, 'error'); assert.equal(frames.size, 0);
const unresolved = structuredClone(world); delete unresolved.assets[0].catalogueRef;
const fallbackScenes = new HistoricalJourneyScenes(session, { portunus: unresolved });
time = { start: { year: 100 } };
assert.match(fallbackScenes.resolve(['exterior'], journey, time).warning, /unavailable/);
assert.equal(applied.descriptors.length, 0);
fallbackScenes.release();
const outside = structuredClone(journey); outside.scope.time = { start: { year: 101 } };
player.load(outside); player.jump(1); assert.equal(applied.descriptors.length, 0); assert.match(player.snapshot.warning, /unavailable/);
assert.match(historicalModelStatus(true, true, 'error', ['404']), /could not load/);
assert.match(historicalModelStatus(true, true, 'waiting-terrain', []), /waiting/);
assert.match(historicalModelStatus(true, false, 'ready', []), /approach/);
assert.match(historicalModelStatus(false, true, 'ready', []), /hidden/);
assert.match(historicalModelStatus(true, true, 'ready', []), /visible/);
const { SettlementScene } = await mod('map/settlements/SettlementScene');
const { selectHistoricalWorld } = await mod('lib/history/selection');
const definition = selectHistoricalWorld(world, { start: { year: 100 } }, { explicitLayoutId: world.layouts[0].id }).descriptors[0].definition;
let modelStatus;
const missingModel = new SettlementScene(definition, status => modelStatus = status, () => {}, { acquire: async () => { throw Error('simulated GLB 404'); } });
await missingModel.load(); missingModel.updateTerrain(() => ({ displayMeters: 0, readiness: 'confirmed' }));
assert.equal(modelStatus.loaded, 0); assert.match(modelStatus.errors[0], /404/);
assert.equal(missingModel.scene.getObjectByName('building:portunus'), undefined);
assert.match(historicalModelStatus(true, true, modelStatus.state, modelStatus.errors), /could not load/);
missingModel.dispose();
player.dispose(); session.dispose(); assert.equal(applied, null); assert.equal(frames.size, 0);
assert.equal(requests, 1, 'Journey uses registered bundled data without implicit fetching');
console.log('Portunus journey: sourced scenario, exact catalogue reuse, overview/detail scope, interrupt/explore/date/restore, jump/restart/completion/exit/switch/dispose, missing/required/outside guards and runtime status pass.');
