import './glb-node-images.mjs';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import * as THREE from 'three';
import { GLTFLoader } from 'three/addons/loaders/GLTFLoader.js';
import { loadTypescript } from './lib/load-typescript.mjs';
const { assetRegistry } = await import(await loadTypescript('lib/assets/registry'));
const { validateAssetCatalogue, catalogueStatus } = await import(await loadTypescript('lib/assets/catalogueValidation'));
const catalogue = validateAssetCatalogue(JSON.parse(await readFile('lib/assets/catalogue.json', 'utf8')));
const entry = catalogue.entries.find(e => e.id === 'catalogue:hercules-victor-exterior');
assert.ok(entry, 'catalogue entry exists');
assert.equal(entry.period.start.year, 100);
assert.equal(entry.placeId, 'place:temple-of-hercules-victor');
assert.ok(entry.features.some(f => f.certainty === 'inferred' && /roof/i.test(f.title)), 'roof is labelled inferred');
assert.ok(entry.features.every(f => f.sourceIds.length), 'every feature cites a source');
assert.ok(entry.sources.some(s => /palladio/i.test(s.id)) && entry.limitations.length >= 3);
assert.equal(catalogueStatus(catalogue, entry), 'usable');
const asset = assetRegistry[entry.rendering.registryId];
assert.ok(asset, 'registry binding');
const bytes = await readFile(`public/assets/${asset.path}`);
assert.equal(createHash('sha256').update(bytes).digest('hex'), entry.rendering.sha256, 'model matches pinned hash');
const gltf = await new GLTFLoader().parseAsync(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength), '');
const size = new THREE.Box3().setFromObject(gltf.scene).getSize(new THREE.Vector3());
asset.dimensionsMeters.forEach((d, i) => assert.ok(Math.abs(d - size.toArray()[i]) < 0.05, `registry dimension ${i} matches model`));
assert.ok(Math.abs(size.x - 17.8) < 0.05 && size.y > 15 && size.y < 19, 'plausible tholos proportions (14.8 m stylobate, 10.65 m columns)');
let meshes = 0; gltf.scene.traverse(o => { if (o.isMesh) { meshes++; assert.equal(o.material.map, null, 'no image textures'); } });
assert.ok(meshes <= 8, 'low draw count');
await readFile(`public/assets/${entry.rights.provenancePath}`);
console.log('Hercules Victor exterior: catalogue pin, evidence labels, hash, registry dimensions, no textures and provenance pass.');
