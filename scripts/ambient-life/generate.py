"""Project-owned articulated adult, authored directly in GLTF Y-up metres.
Blender --background --factory-startup --python scripts/ambient-life/generate.py
Animation is restrained runtime joint motion; no rig, third-party assets or APIs.
"""
from pathlib import Path
import bpy
bpy.ops.object.select_all(action='SELECT')
bpy.ops.object.delete(use_global=False)
OUT = Path(__file__).resolve().parents[2] / 'public/assets/characters'
OUT.mkdir(parents=True, exist_ok=True)
def material(name, rgb):
    m = bpy.data.materials.new(name); m.diffuse_color = (*rgb, 1); m.use_nodes = True
    m.node_tree.nodes['Principled BSDF'].inputs['Base Color'].default_value = (*rgb, 1)
    m.node_tree.nodes['Principled BSDF'].inputs['Roughness'].default_value = .95
    return m
cloth=material('undyed-ochre-linen',(.37,.29,.18)); skin=material('skin',(.48,.30,.19))
leather=material('worn-leather',(.13,.085,.05)); hair=material('dark-hair',(.065,.045,.03))
def joint(name, pos, parent=None):
    o=bpy.data.objects.new(name,None); bpy.context.collection.objects.link(o); o.parent=parent; o.location=pos; return o
def ellipsoid(name,pos,size,mat,parent):
    bpy.ops.mesh.primitive_uv_sphere_add(segments=10,ring_count=6,location=(0,0,0))
    o=bpy.context.object
    for axis in range(3):
        extent=max(abs(v.co[axis]) for v in o.data.vertices)
        for v in o.data.vertices: v.co[axis]/=extent
    o.name=name; o.parent=parent; o.location=pos; o.scale=size
    o.data.materials.append(mat)
    return o
def tunic_section(name, bottom, top, lower, upper, parent):
    # Restrained sewn silhouette and a level hem, rather than a spherical garment.
    import math
    vertices=[]
    for y, (rx, rz) in [(bottom,lower),(top,upper)]:
        vertices.extend((rx*math.cos(i*math.tau/10),y,rz*math.sin(i*math.tau/10)/math.sin(math.tau*2/10)) for i in range(10))
    faces=[tuple(range(10)),tuple(reversed(range(10,20)))]
    faces.extend((i,i+10,(i+1)%10+10,(i+1)%10) for i in range(10))
    mesh=bpy.data.meshes.new(name); mesh.from_pydata(vertices,[],faces); mesh.update()
    obj=bpy.data.objects.new(name,mesh); bpy.context.collection.objects.link(obj); obj.parent=parent; obj.data.materials.append(cloth)
root=joint('villager',(0,0,0))
body=joint('body',(0,0,0),root)
tunic_section('tunic-bodice',1.04,1.46,(.20,.13),(.245,.135),body)
tunic_section('tunic-skirt',.70,1.065,(.26,.16),(.20,.13),body)
ellipsoid('belt',(0,1.055,0),(.255,.035,.145),leather,body)
ellipsoid('neck',(0,1.49,0),(.065,.085,.065),skin,body)
ellipsoid('head',(0,1.635,.008),(.105,.135,.10),skin,body)
ellipsoid('hair',(0,1.705,-.014),(.108,.078,.098),hair,body)
ellipsoid('nose',(0,1.635,.103),(.023,.034,.035),skin,body)
for side,x in [('left',-.125),('right',.125)]:
    leg=joint(side+'Leg',(x,.83,0),root)
    ellipsoid(side+'Shin',(0,-.37,0),(.066,.39,.068),skin,leg)
    ellipsoid(side+'Sandal',(0,-.79,.045),(.083,.04,.145),leather,leg)
    ellipsoid(side+'Strap',(0,-.747,.025),(.075,.015,.06),leather,leg)
    arm=joint(side+'Arm',(x*2,1.41,0),body)
    ellipsoid(side+'Sleeve',(0,-.10,0),(.085,.15,.095),cloth,arm)
    ellipsoid(side+'Forearm',(0,-.36,.015),(.046,.20,.047),skin,arm)
    ellipsoid(side+'Hand',(0,-.56,.025),(.047,.065,.038),skin,arm)
# Bake the small palette into vertex colors so every section shares one material.
shared=material('villager-matte-palette',(1,1,1))
node=shared.node_tree.nodes.new('ShaderNodeVertexColor'); node.layer_name='Color'
shared.node_tree.links.new(node.outputs['Color'],shared.node_tree.nodes['Principled BSDF'].inputs['Base Color'])
for obj in list(bpy.data.objects):
    if obj.type!='MESH':continue
    color=obj.data.materials[0].diffuse_color[:]
    attr=obj.data.color_attributes.new(name='Color',type='FLOAT_COLOR',domain='CORNER')
    for c in attr.data:c.color=color
    obj.data.materials.clear();obj.data.materials.append(shared)
# Join each articulated section: five draws per character, immutable shared resources.
for parent in [body]+[o for o in bpy.data.objects if o.type=='EMPTY' and o.name.endswith(('Leg','Arm'))]:
    meshes=[o for o in parent.children if o.type=='MESH']
    bpy.ops.object.select_all(action='DESELECT')
    for o in meshes:o.select_set(True)
    bpy.context.view_layer.objects.active=meshes[0]; bpy.ops.object.join()
bpy.ops.export_scene.gltf(filepath=str(OUT/'roman-villager.glb'),export_format='GLB',export_yup=False,export_animations=False)
(OUT/'PROVENANCE.md').write_text('Project-authored Roman-inspired adult (1.77 m), tunic, belt and leather sandals. Generated by scripts/ambient-life/generate.py. No imported content. Repository terms apply. GLB is Y-up, +Z forward, feet at zero. Articulated joints animated by AmbientLifeView.ts.\n')
